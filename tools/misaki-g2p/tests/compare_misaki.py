"""Agreement gate between the native misaki_g2p and the pinned Python misaki.

Paradee-8M was trained on phonemes from misaki 0.9.4 configured as in
paradee/tts.py. This script runs that exact configuration (versions pinned in
../pins.json, "reference_python") and the native misaki-g2p-cli, and compares
them per word and per sentence.

  reference  run Python misaki on the corpus and write the fixture
             (tests/fixtures/reference.txt + .sha256) the CTest gate reads
  compare    run misaki-g2p-cli --dump and score it against a fixture,
             writing a report that lists every mismatch
  extended   reference + compare on more WikiText sentences (not a gate:
             shows how well the rules generalise beyond the gate corpus)
  numbers    check the native number words against num2words

Reference environment (Python 3.12):
  pip install misaki==0.9.4 spacy==3.8.16 num2words==0.5.14 phonemizer-fork==3.3.2 \\
      espeakng-loader==0.2.4 addict regex \\
      https://github.com/explosion/spacy-models/releases/download/en_core_web_sm-3.8.0/en_core_web_sm-3.8.0-py3-none-any.whl
num2words is LGPL-2.1 and only used here; the native number code is independent.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PINS = json.load(open(os.path.join(ROOT, "pins.json"), encoding="utf-8"))
CORPUS = [
    ("paradee_samples", os.path.join(HERE, "corpus", "paradee_samples.txt")),
    ("wikitext_heldout_200", os.path.join(HERE, "corpus", "wikitext_heldout_200.txt")),
    ("eliza_android_sentences", os.path.join(HERE, "corpus", "eliza_android_sentences.txt")),
]
AGENT_CORPUS = [("agent_style", os.path.join(HERE, "corpus", "agent_style.txt"))]
WORD_GATE = 0.995
SENTENCE_GATE = 0.98


def paradee_vocab():
    # Paradee-8M v1.0 config.json vocab keys (see pins.json paradee_model)
    return set(";:,.!?—…\"()“” ̃ʣʥʦʨᵝꭧAIOQSTWYᵊ"
               "abcdefhijklmnopqrstuvwxyzɑɐɒæβɔɕçɖðʤə"
               "ɚɛɜɟɡɥɨɪʝɯɰŋɳɲɴø"
               "ɸθœɹɾɻʁɽʂʃʈʧʊʋʌɣ"
               "ɤχʎʒʔˈˌːʰʲ↓→↗↘ᵻ")


VOCAB = paradee_vocab()


def vocab_filter(s):
    """What paradee feeds the model: generate_from_phonemes keeps `c in vocab`."""
    return "".join(c for c in s if c in VOCAB)


def load_corpus(corpus=CORPUS):
    out = []
    for name, path in corpus:
        with open(path, encoding="utf-8") as f:
            for i, line in enumerate(f):
                line = line.rstrip("\n")
                if line.strip():
                    out.append((f"{name}:{i + 1}", line))
    return out


def make_g2p():
    """misaki exactly as paradee/tts.py builds it."""
    import importlib.metadata as md
    want = PINS["reference_python"]
    got = {k: md.version(k) for k in ("misaki", "spacy", "num2words", "phonemizer-fork", "espeakng-loader", "en_core_web_sm")}
    for k, v in got.items():
        pin = want[k] if k in want else None
        if pin and v != pin:
            raise SystemExit(f"{k} {v} != pinned {pin}")
    import espeakng_loader
    import shutil
    import tempfile
    from phonemizer.backend.espeak.wrapper import EspeakWrapper
    data = espeakng_loader.get_data_path()
    if len(data) > 120:
        # libespeak-ng keeps the data path in a 160-byte buffer; long venv
        # paths fail with a misleading "No such file" error.
        tmp = tempfile.mkdtemp(prefix="espeak")
        shutil.copytree(data, os.path.join(tmp, "espeak-ng-data"))
        data = os.path.join(tmp, "espeak-ng-data")
    from misaki import en, espeak  # noqa: E402  (misaki/espeak.py sets the library on import)
    EspeakWrapper.set_data_path(data)
    return en.G2P(trf=False, british=False, fallback=espeak.EspeakFallback(british=False), unk="")


def paradee_chunks(phonemize, text, max_phonemes=510):
    import re
    for sentence in re.split(r"(?<=[.!?…])\s+|\n+", text.strip()):
        if not sentence.strip():
            continue
        ps = phonemize(sentence)
        while len(ps) > max_phonemes:
            cut = ps.rfind(" ", 0, max_phonemes)
            cut = cut if cut > 0 else max_phonemes
            yield ps[:cut]
            ps = ps[cut:].lstrip()
        if ps:
            yield ps


def run_reference(items):
    g2p = make_g2p()
    recs = []
    for sid, text in items:
        ps, toks = g2p(text)
        chunks = list(paradee_chunks(lambda s: g2p(s)[0], text))
        recs.append(dict(id=sid, text=text, ps=ps, chunks=chunks,
                         toks=[(t.text, t.phonemes or "", t.whitespace, t.tag) for t in toks]))
    return recs


def write_fixture(recs, path):
    lines = [
        "# misaki 0.9.4 reference phonemes for tools/misaki-g2p (generated by tests/compare_misaki.py reference).",
        "# Configuration: en.G2P(trf=False, british=False, fallback=espeak.EspeakFallback(british=False), unk='')",
        "# Lines: S id<TAB>text, P phonemes, C paradee chunk, T token<TAB>phonemes<TAB>whitespace<TAB>tag.",
        "# Phonemes are as misaki returns them; the gate compares them after Paradee's vocab filter.",
    ]
    for r in recs:
        for field in (r["text"],) + tuple(r["chunks"]):
            if "\t" in field or "\n" in field:
                raise SystemExit(f"{r['id']}: tab or newline in fixture field")
        lines.append(f"S\t{r['id']}\t{r['text']}")
        lines.append(f"P\t{r['ps']}")
        for c in r["chunks"]:
            lines.append(f"C\t{c}")
        for t in r["toks"]:
            lines.append("T\t" + "\t".join(t))
    data = ("\n".join(lines) + "\n").encode("utf-8")
    with open(path, "wb") as f:
        f.write(data)
    digest = hashlib.sha256(data).hexdigest()
    with open(path + ".sha256", "w") as f:
        f.write(f"{digest}  {os.path.basename(path)}\n")
    return digest


def read_fixture(path):
    recs = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            kind, _, rest = line.partition("\t")
            if kind == "S":
                sid, _, text = rest.partition("\t")
                recs.append(dict(id=sid, text=text, ps="", chunks=[], toks=[]))
            elif kind == "P":
                recs[-1]["ps"] = rest
            elif kind == "C":
                recs[-1]["chunks"].append(rest)
            elif kind == "T":
                parts = rest.split("\t")
                while len(parts) < 4:
                    parts.append("")
                recs[-1]["toks"].append(tuple(parts[:4]))
    return recs


def run_native(cli, lex, espeak, texts):
    cmd = [cli, "--lex", lex, "--dump"]
    if espeak:
        cmd += ["--espeak", espeak]
    out = subprocess.run(cmd, input="\n".join(texts) + "\n", capture_output=True, text=True, check=True).stdout
    recs = []
    for line in out.split("\n"):
        if not line:
            continue
        kind, _, rest = line.partition("\t")
        if kind == "S":
            recs.append(dict(text=rest, ps="", chunks=[], toks=[]))
        elif kind == "P":
            recs[-1]["ps"] = rest
        elif kind == "C":
            recs[-1]["chunks"].append(rest)
        elif kind == "T":
            parts = rest.split("\t")
            while len(parts) < 4:
                parts.append("")
            recs[-1]["toks"].append(tuple(parts[:4]))
    if len(recs) != len(texts):
        raise SystemExit(f"native produced {len(recs)} records for {len(texts)} inputs")
    return recs


def align(a, b):
    """LCS alignment of two token-text sequences -> list of (i, j)."""
    n, m = len(a), len(b)
    dp = [[0] * (m + 1) for _ in range(n + 1)]
    for i in range(n - 1, -1, -1):
        for j in range(m - 1, -1, -1):
            dp[i][j] = dp[i + 1][j + 1] + 1 if a[i] == b[j] else max(dp[i + 1][j], dp[i][j + 1])
    i = j = 0
    pairs = []
    while i < n and j < m:
        if a[i] == b[j]:
            pairs.append((i, j))
            i += 1
            j += 1
        elif dp[i + 1][j] >= dp[i][j + 1]:
            i += 1
        else:
            j += 1
    return pairs


def is_word(text):
    return any(c.isalnum() for c in text)


def score(ref, nat):
    words = word_ok = sents = sent_ok = 0
    mismatches = []
    for r, n in zip(ref, nat):
        sents += 1
        want = vocab_filter(r["ps"])
        ok = want == n["ps"] and [vocab_filter(c) for c in r["chunks"]] == n["chunks"]
        sent_ok += ok
        rt = [t[0] for t in r["toks"]]
        nt = [t[0] for t in n["toks"]]
        pairs = dict(align(rt, nt))
        bad = []
        for i, tok in enumerate(r["toks"]):
            if not is_word(tok[0]):
                continue
            words += 1
            j = pairs.get(i)
            got = n["toks"][j][1] if j is not None else None
            if got is not None and vocab_filter(tok[1]) == got:
                word_ok += 1
            else:
                bad.append((tok[0], tok[3], vocab_filter(tok[1]), got, n["toks"][j][3] if j is not None else "-"))
        if not ok or bad:
            mismatches.append(dict(id=r.get("id", ""), text=r["text"], ref=want, nat=n["ps"], words=bad))
    return dict(words=words, word_ok=word_ok, sents=sents, sent_ok=sent_ok, mismatches=mismatches)


def report(s, path, title):
    wr = s["word_ok"] / max(1, s["words"])
    sr = s["sent_ok"] / max(1, s["sents"])
    passed = wr >= WORD_GATE and sr >= SENTENCE_GATE
    lines = [f"# {title}", "",
             f"words:     {s['word_ok']}/{s['words']} = {wr:.4%} (gate >= {WORD_GATE:.1%})",
             f"sentences: {s['sent_ok']}/{s['sents']} = {sr:.4%} (gate >= {SENTENCE_GATE:.0%})",
             f"result:    {'PASS' if passed else 'FAIL'}", "",
             f"## mismatches ({len(s['mismatches'])} sentences)", ""]
    for m in s["mismatches"]:
        lines.append(f"- {m['id']} {m['text']}")
        lines.append(f"  misaki: {m['ref']}")
        lines.append(f"  native: {m['nat']}")
        for w, tag, want, got, ntag in m["words"]:
            lines.append(f"    word {w!r} [{tag} / native {ntag}]: misaki {want!r} native {got!r}")
    text = "\n".join(lines) + "\n"
    if path:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    print("\n".join(lines[:5]))
    return passed


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("reference")
    r.add_argument("--out", default=os.path.join(HERE, "fixtures", "reference.txt"))
    c = sub.add_parser("compare")
    c.add_argument("--cli", required=True)
    c.add_argument("--lex", required=True)
    c.add_argument("--espeak", required=True, help="espeak-ng-data directory (eSpeak NG 1.52.0)")
    c.add_argument("--fixture", default=os.path.join(HERE, "fixtures", "reference.txt"))
    c.add_argument("--report")
    e = sub.add_parser("extended")
    e.add_argument("--cli", required=True)
    e.add_argument("--lex", required=True)
    e.add_argument("--espeak", required=True)
    e.add_argument("--wikitext", required=True, help="paradee training/data/wikitext_sents.json")
    e.add_argument("--start", type=int, default=200)
    e.add_argument("--count", type=int, default=1000)
    e.add_argument("--report")
    nm = sub.add_parser("numbers")
    nm.add_argument("--cli", required=True)
    a = ap.parse_args()

    if a.cmd == "reference":
        recs = run_reference(load_corpus())
        digest = write_fixture(recs, a.out)
        print(f"{a.out}: {len(recs)} sentences, sha256 {digest}")
        agent_out = os.path.join(os.path.dirname(a.out), "agent_style.txt")
        recs = run_reference(load_corpus(AGENT_CORPUS))
        digest = write_fixture(recs, agent_out)
        print(f"{agent_out}: {len(recs)} sentences, sha256 {digest}")
    elif a.cmd == "compare":
        ref = read_fixture(a.fixture)
        nat = run_native(a.cli, a.lex, a.espeak, [x["text"] for x in ref])
        ok = report(score(ref, nat), a.report, "misaki-g2p agreement gate")
        sys.exit(0 if ok else 1)
    elif a.cmd == "extended":
        data = open(a.wikitext, "rb").read()
        if hashlib.sha256(data).hexdigest() != PINS["paradee"]["wikitext_sents_json"]["sha256"]:
            raise SystemExit("wikitext_sents.json does not match the pin")
        sents = json.loads(data)[a.start:a.start + a.count]
        ref = run_reference([(f"wikitext:{a.start + i}", s) for i, s in enumerate(sents)])
        nat = run_native(a.cli, a.lex, a.espeak, [x["text"] for x in ref])
        report(score(ref, nat), a.report, f"misaki-g2p extended check (wikitext {a.start}..{a.start + a.count})")
    elif a.cmd == "numbers":
        from num2words import num2words
        import random
        rnd = random.Random(1234)
        cases = []
        vals = list(range(0, 2101)) + [rnd.randrange(0, 10 ** rnd.randrange(1, 37)) for _ in range(3000)]
        for v in vals:
            cases.append(("cardinal", str(v), num2words(v)))
            cases.append(("ordinal", str(v), num2words(v, to="ordinal")))
        for v in range(1, 10000):
            cases.append(("year", str(v), num2words(v, to="year")))
        for _ in range(2000):
            ip = rnd.randrange(0, 10 ** rnd.randrange(1, 7))
            fp = str(rnd.randrange(0, 10 ** rnd.randrange(1, 6))).rjust(rnd.randrange(1, 6), "0")
            txt = f"{ip}.{fp}"
            cases.append(("float", txt, num2words(float(txt))))
        out = subprocess.run([a.cli, "--numbers"], input="\n".join(f"{k} {v}" for k, v, _ in cases) + "\n",
                             capture_output=True, text=True, check=True).stdout.split("\n")
        bad = [(k, v, want, got) for (k, v, want), got in zip(cases, out) if want != got]
        for b in bad[:40]:
            print("MISMATCH", b)
        print(f"numbers: {len(cases) - len(bad)}/{len(cases)} equal to num2words")
        sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
