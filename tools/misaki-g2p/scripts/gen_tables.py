#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Generate the character tables and tokenizer exceptions compiled into
misaki_g2p (src/unicode-tables.inc, src/spacy-en-rules.inc).

misaki leans on Python string methods (isalpha, lower, upper, isdigit,
unicodedata.numeric, NFKC) and on spaCy's English tokenizer. The C++ port
reproduces both from these tables, so they are generated from the exact
versions misaki 0.9.4 ran with when Paradee's training data was made
(pins.json: python 3.12 / Unicode 15.0, spacy 3.8.16, en_core_web_sm 3.8.0).
spaCy is MIT-licensed (LICENSES/spaCy-MIT.txt); the exception list is data
from spacy/lang/en/tokenizer_exceptions.py and spacy/lang/tokenizer_exceptions.py.

usage: python3 scripts/gen_tables.py   (rewrites both .inc files next to src/)
"""
import json
import os
import re
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")
PINS = json.load(open(os.path.join(HERE, "..", "pins.json"), encoding="utf-8"))

import regex  # noqa: E402  (the module misaki's subtokenizer uses)
import spacy  # noqa: E402
from spacy.lang import char_classes as cc  # noqa: E402

MAXCP = 0x110000


def check_versions():
    want_py = PINS["generator"]["python"]
    got_py = "%d.%d" % sys.version_info[:2]
    if got_py != want_py:
        raise SystemExit(f"python {got_py} != pinned {want_py} (Unicode tables would change)")
    if spacy.__version__ != PINS["generator"]["spacy"]:
        raise SystemExit(f"spacy {spacy.__version__} != pinned {PINS['generator']['spacy']}")


def ranges(pred):
    out = []
    start = None
    for cp in range(MAXCP):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAXCP - 1))
    return out


def emit_ranges(f, name, rs):
    f.write(f"static const CpRange {name}[] = {{\n")
    for i in range(0, len(rs), 6):
        f.write("    " + " ".join("{0x%X, 0x%X}," % r for r in rs[i:i + 6]) + "\n")
    f.write("};\n\n")


def cxx_u32(s):
    return 'U"' + "".join("\\U%08X" % ord(c) for c in s) + '"'


def cxx_u8(s):
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if 0x20 <= b < 0x7F and c not in '"\\?':
            out.append(c)
        else:
            out.append("\\x%02X\"\"" % b)
    return '"' + "".join(out) + '"'


def cls(pattern_class):
    rx = re.compile("[" + pattern_class + "]")
    return lambda ch: rx.fullmatch(ch) is not None


def gen_unicode():
    path = os.path.join(SRC, "unicode-tables.inc")
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/gen_tables.py from Python %s (Unicode %s), regex %s and\n"
                "// spaCy %s char_classes. Do not edit.\n\n"
                % ("%d.%d.%d" % sys.version_info[:3], unicodedata.unidata_version, regex.__version__, spacy.__version__))
        # Python str predicates
        emit_ranges(f, "kPyAlpha", ranges(str.isalpha))
        emit_ranges(f, "kPySpace", ranges(str.isspace))
        # str.isdigit with unicodedata.numeric values
        f.write("static const CpDigit kPyDigit[] = {\n")
        items = [(cp, unicodedata.numeric(chr(cp))) for cp in range(MAXCP)
                 if not (0xD800 <= cp <= 0xDFFF) and chr(cp).isdigit()]
        for i in range(0, len(items), 8):
            f.write("    " + " ".join("{0x%X, %d}," % (cp, int(v)) for cp, v in items[i:i + 8]) + "\n")
        f.write("};\n\n")
        # case maps (1:1 and multi)
        for name, fn in (("Lower", str.lower), ("Upper", str.upper)):
            one, multi = [], []
            for cp in range(MAXCP):
                if 0xD800 <= cp <= 0xDFFF:
                    continue
                c = chr(cp)
                m = fn(c)
                if m == c:
                    continue
                if len(m) == 1:
                    one.append((cp, ord(m)))
                else:
                    multi.append((cp, m))
            f.write(f"static const CpMap kPy{name}One[] = {{\n")
            for i in range(0, len(one), 6):
                f.write("    " + " ".join("{0x%X, 0x%X}," % p for p in one[i:i + 6]) + "\n")
            f.write("};\n\n")
            f.write(f"static const CpMulti kPy{name}Multi[] = {{\n")
            for cp, m in multi:
                f.write("    {0x%X, %s},\n" % (cp, cxx_u32(m)))
            f.write("};\n\n")
        # Python title-case first char (str.capitalize uses title case for the first char)
        one = []
        for cp in range(MAXCP):
            if 0xD800 <= cp <= 0xDFFF:
                continue
            c = chr(cp)
            t = c.capitalize()
            if t != c and len(t) == 1:
                one.append((cp, ord(t)))
        f.write("static const CpMap kPyTitleOne[] = {\n")
        for i in range(0, len(one), 6):
            f.write("    " + " ".join("{0x%X, 0x%X}," % p for p in one[i:i + 6]) + "\n")
        f.write("};\n\n")
        # regex-module general categories used by misaki's subtokenizer
        cat = unicodedata.category
        emit_ranges(f, "kCatL", ranges(lambda ch: cat(ch).startswith("L")))
        emit_ranges(f, "kCatLu", ranges(lambda ch: cat(ch) == "Lu"))
        emit_ranges(f, "kCatLl", ranges(lambda ch: cat(ch) == "Ll"))
        emit_ranges(f, "kCatNd", ranges(lambda ch: cat(ch) == "Nd"))
        # NFKC: per-code-point mapping plus canonical pair composition
        f.write("static const CpMulti kNfkc[] = {\n")
        for cp in range(MAXCP):
            if 0xD800 <= cp <= 0xDFFF:
                continue
            c = chr(cp)
            n = unicodedata.normalize("NFKC", c)
            if n != c:
                f.write("    {0x%X, %s},\n" % (cp, cxx_u32(n)))
        f.write("};\n\n")
        pairs = []
        for cp in range(MAXCP):
            if 0xD800 <= cp <= 0xDFFF:
                continue
            c = chr(cp)
            d = unicodedata.decomposition(c)
            if not d or d.startswith("<"):
                continue
            parts = [int(x, 16) for x in d.split()]
            if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == c:
                pairs.append((parts[0], parts[1], cp))
        pairs.sort()
        f.write("static const CpCompose kCompose[] = {\n")
        for i in range(0, len(pairs), 4):
            f.write("    " + " ".join("{0x%X, 0x%X, 0x%X}," % p for p in pairs[i:i + 4]) + "\n")
        f.write("};\n\n")
        f.write("static const CpMap kCombiningClass[] = {\n")
        ccs = [(cp, unicodedata.combining(chr(cp))) for cp in range(MAXCP)
               if not (0xD800 <= cp <= 0xDFFF) and unicodedata.combining(chr(cp))]
        for i in range(0, len(ccs), 8):
            f.write("    " + " ".join("{0x%X, %d}," % p for p in ccs[i:i + 8]) + "\n")
        f.write("};\n\n")
        # spaCy character classes
        emit_ranges(f, "kSpacyAlpha", ranges(cls(cc.ALPHA)))
        emit_ranges(f, "kSpacyAlphaLower", ranges(cls(cc.ALPHA_LOWER)))
        emit_ranges(f, "kSpacyAlphaUpper", ranges(cls(cc.ALPHA_UPPER)))
        # lookbehind class of the suffix rule (?<=[0-9{al}{e}{p}(?:{q})])\.
        from spacy.lang import punctuation as sp
        dot_rule = [r for r in sp.TOKENIZER_SUFFIXES if r.startswith("(?<=[0-9") and r.endswith("])\\.")]
        assert len(dot_rule) == 1, dot_rule
        rx = re.compile(dot_rule[0])
        emit_ranges(f, "kSpacySuffixDotPre", ranges(lambda ch: (m := rx.search(ch + ".")) is not None and m.start() == 1))
        icons = cc.LIST_ICONS[0]
        assert icons.startswith("[") and icons.endswith("]"), icons[:20]
        emit_ranges(f, "kSpacyIcons", ranges(cls(icons[1:-1])))
    print(path)


def gen_rules():
    nlp = spacy.blank("en")
    rules = nlp.tokenizer.rules
    path = os.path.join(SRC, "spacy-en-rules.inc")
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/gen_tables.py from spaCy %s English tokenizer exceptions\n"
                "// (MIT, see LICENSES/spaCy-MIT.txt). Do not edit. Each entry is the exception\n"
                "// string and its token pieces separated by \\x1F.\n\n" % spacy.__version__)
        f.write("static const char * const kSpacyRules[] = {\n")
        for k in sorted(rules, key=lambda s: s.encode("utf-8")):
            pieces = [x[65] for x in rules[k]]  # 65 == spacy.attrs.ORTH
            assert "".join(pieces) == k, (k, pieces)
            f.write("    %s,\n" % cxx_u8(k + "\x1f" + "\x1f".join(pieces)))
        f.write("};\n")
    print(path, len(rules))


if __name__ == "__main__":
    check_versions()
    gen_unicode()
    gen_rules()
